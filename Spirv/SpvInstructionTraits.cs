    public static bool HasResultType(ushort opCode) => GetResultLayout(opCode) == SpvResultLayout.TypeAndId;

    public static bool HasResultId(ushort opCode) => GetResultLayout(opCode) != SpvResultLayout.None;

    public static SpvResultLayout GetResultLayout(ushort opCode)
        => Array.BinarySearch(ResultIdOnlyOpcodes, (SpvOperandLayoutOpcode)opCode) >= 0
            ? SpvResultLayout.Id
            : Array.BinarySearch(ResultTypeAndIdOpcodes, (SpvOperandLayoutOpcode)opCode) >= 0
                ? SpvResultLayout.TypeAndId
                : SpvResultLayout.None;

    public static int? GetResultTypeIdIndex(SpirvInstruction instruction)
    {
        if (GetResultLayout(instruction.OpCode) != SpvResultLayout.TypeAndId)
        {
            return null;
        }

        EnsureOperandCount(instruction, minimumWordCount: 2, "result type id");
        return 1;
    }

    public static int? GetResultIdIndex(SpirvInstruction instruction)
    {
        SpvResultLayout layout = GetResultLayout(instruction.OpCode);
        if (layout == SpvResultLayout.None)
        {
            return null;
        }

        int index = layout == SpvResultLayout.TypeAndId ? 2 : 1;
        EnsureOperandCount(instruction, index + 1, "result id");
        return index;
    }

    private static void EnsureOperandCount(SpirvInstruction instruction, int minimumWordCount, string operandName)
    {
        if (instruction.WordCount < minimumWordCount)
        {
            throw new InvalidOperationException($"Malformed SPIR-V instruction missing {operandName}: opCode={instruction.OpCode} wordCount={instruction.WordCount} offset={instruction.Offset} words=[{instruction.FormatWords()}]");
        }
    }
